#!/usr/bin/env python3
"""Regenerate references/ from the GMP repository docs and examples.

Run from anywhere:  python skills/gmp/build_references.py
The skill is self-contained after this, so it can be copied into ~/.claude/skills/ or a project's .claude/skills/.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
REF = os.path.join(HERE, 'references')


def read(*p):
    with open(os.path.join(ROOT, *p), encoding='utf-8') as f:
        return f.read()


def write(name, text):
    os.makedirs(REF, exist_ok=True)
    with open(os.path.join(REF, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def section(md, start, end):
    """Text from heading `start` up to (not including) heading `end`."""
    i = md.index(start)
    j = md.index(end, i)
    return md[i:j].rstrip() + '\n'


GENERATED = '<!-- Generated by build_references.py from the GMP repository. Do not edit by hand. -->\n\n'

# ---------------------------------------------------------------- schema.md
write('schema.md', GENERATED + read('docs', 'schema.md'))

# ---------------------------------------------------------------- cpp-api.md
readme = read('README.md')
api = section(readme, '## Generated C++ API', '## Project layout')
api = re.sub(r'\]\(#computed-values\)', '](schema.md)', api)  # anchors that live in the README only
write('cpp-api.md', GENERATED + '# GMP generated C++ API, streaming, errors, build integration\n\n'
      'Contents: generated structs / views / protocols · streaming · errors · building · CMake · gmpc.\n\n' + api)

# ---------------------------------------------------------------- recipes.md
def recipe(title, when, yaml_path, notes, code=None, code_lang='cpp'):
    out = [f'## {title}\n', f'**Use when:** {when}\n',
           f'```yaml\n# {"/".join(yaml_path)}\n{read(*yaml_path).rstrip()}\n```\n']
    if notes:
        out.append(notes.strip() + '\n')
    if code:
        out.append(f'```{code_lang}\n{code.rstrip()}\n```\n')
    return '\n'.join(out) + '\n'


tel_main = read('examples', 'binary_telemetry', 'main.cpp')
nmea_main = read('examples', 'nmea_text', 'main.cpp')
can_main = read('examples', 'bitpacked_can', 'main.cpp')
sht_main = read('examples', 'sensirion_sht4x', 'main.cpp')
motor_main = read('examples', 'reserved_sync', 'main.cpp')
meter_main = read('examples', 'custom_codec', 'main.cpp')
meter_hpp = read('examples', 'custom_codec', 'meter_codecs.hpp')


recipes = [
    '# GMP recipes\n',
    'Complete schemas from the GMP repository `examples/` (each one compiles and runs there), with the C++ that uses them.\n'
    'Pick the closest one, copy it, and adapt it.\n',
    'Contents:\n'
    '1. Framed binary link: sync, header, length, CRC, several message types, streaming\n'
    '2. Text protocol (NMEA 0183): tokens, XOR checksum, optional fields\n'
    '3. CAN payload with bit-packed Intel signals, and a fixed-size framed link\n'
    '4. I2C sensor with a CRC after every word, unit conversions and a computed value\n'
    '5. Serial link where 0x80 is a reserved sync byte (byte stuffing)\n'
    '6. Custom field codec and custom checksum in C++\n',
    recipe('1. Framed binary link (length-prefixed, CRC, several messages)',
           'a UART / TCP / radio link with a sync word, a header holding a message id and a length, and a CRC.',
           ('examples', 'binary_telemetry', 'telemetry.yaml'),
           '- `message_type: { field: id }` picks the message by its `type_id`; the protocol fills `id` and `length` on encode.\n'
           '- `when:` makes `fault` an `std::optional` that exists only in fault mode.\n'
           '- The stream parser skips noise (`BadSync`) and corrupt frames (`BadChecksum`) and keeps going.',
           tel_main),
    recipe('2. Text protocol: NMEA 0183',
           'ASCII sentences such as `$GPGGA,...*47\\r\\n`: delimited frames, comma-separated tokens, hex checksum.',
           ('examples', 'nmea_text', 'nmea.yaml'),
           '- `format: text` in `defaults`; each field is one token, `{ pad: 4 }` skips four tokens.\n'
           '- `message_type: { token: 0 }` matches the first token (`GPGGA`) against `type_id`.\n'
           '- Text view accessors parse on demand and return `gmp::Result<T>` (optional fields: `Result<std::optional<T>>`).',
           nmea_main),
    recipe('3. CAN payload with bit-packed signals',
           'a DBC-style CAN frame (Intel `@1` = `lsb_first`, little endian), or any register map with sub-byte fields.',
           ('examples', 'bitpacked_can', 'can.yaml'),
           '- `framing: { type: none }`: the 8 data bytes are the frame (the CAN controller already framed it).\n'
           '- Bit fields take `type`, `enum`, `scale`, `offset` and `const`; `{ pad: N }` reserves bits.\n'
           '- `FixedLink` shows fixed-size framing with a 2-byte sync word and an inline CRC definition.',
           can_main),
    recipe('4. I2C sensor with per-word CRCs (Sensirion SHT4x)',
           'a sensor datasheet where each 16-bit word is followed by its own CRC-8, with conversion formulas and commands.',
           ('examples', 'sensirion_sht4x', 'sht4x.yaml'),
           '- `crc: crc8_nrsc5` on a field = checksum stored right after that value (not a protocol checksum).\n'
           '- `scale` / `offset` implement the datasheet formula; `conversions` adds a second unit (°F).\n'
           '- `computed:` joins `serial_high` / `serial_low`; `set_serial()` splits it back automatically.\n'
           '- Each 1-byte command is its own message with a `const` field. `examples/sensirion_sht4x/sht4x_enum.yaml` shows the\n'
           '  alternative: one `CommandFrame` message with a `strict` enum field.\n'
           '- Responses carry no type id. On I2C, each read is one reply: decode it with `Measurement::decode(bytes)` (no\n'
           '  protocol needed). The fixed-size protocols are only useful when replies arrive on a byte stream.',
           sht_main),
    recipe('5. Reserved sync byte with byte stuffing',
           'a link where a byte value (here 0x80) may only mark the start of a frame, so every other occurrence must be escaped.',
           ('examples', 'reserved_sync', 'motor_link.yaml'),
           '- `escape: { char: 0x81, code: index, reserved: [0x80, 0x81] }`: 0x80 → `81 00`, 0x81 → `81 01`.\n'
           '- Lengths count unescaped bytes; add `counts: wire` to `length` if the device counts escaped bytes\n'
           '  (only with `covers: body` or `body_checksum`).\n'
           '- A raw 0x80 inside a frame means it was cut short: it is dropped (`BadDelimiter`) and parsing restarts there.\n'
           '- Escaped protocols unescape in place: `parse()` takes a mutable buffer.',
           motor_main),
    recipe('6. Custom field codec and custom checksum',
           'a field GMP cannot describe declaratively (BCD dates, packed decimals, proprietary encodings) or a non-standard checksum.',
           ('examples', 'custom_codec', 'meter.yaml'),
           '- The functions are checked at compile time with a clear `static_assert` message if a signature is wrong.\n'
           '- Custom-type view accessors return `gmp::Result<T>` because your decoder can fail.\n\n'
           '```cpp\n// examples/custom_codec/meter_codecs.hpp\n' + meter_hpp.rstrip() + '\n```',
           meter_main),
]
write('recipes.md', GENERATED + '\n'.join(recipes))
print('wrote', ', '.join(sorted(os.listdir(REF))))
