/* gmp/c/checksum.h - checksum and CRC algorithms (same results as gmp/checksum.hpp).
 *
 * Generic CRC (Rocksoft model, width 1..64):
 *     gmsg_crc_params p = { width, refin, refout, poly, init, xorout };
 *     uint64_t crc = gmsg_crc_compute(&p, data, n);
 *     // incremental: c = gmsg_crc_init(&p); c = gmsg_crc_update(&p, c, d, n)...; crc = gmsg_crc_finish(&p, c);
 *
 * Every preset and simple checksum NAME has the same four functions, with the algorithm's value type T:
 *     T gmsg_NAME_init(void);
 *     T gmsg_NAME_update(T state, const uint8_t* data, size_t n);
 *     T gmsg_NAME_finish(T state);
 *     T gmsg_NAME_compute(const uint8_t* data, size_t n);
 * CRC presets also have gmsg_NAME_params(). Presets: crc8 crc8_maxim crc8_autosar crc8_nrsc5 crc15_can crc16_ccitt
 * crc16_xmodem crc16_kermit crc16_x25 crc16_modbus crc16_arc crc24_openpgp crc32 crc32c crc32_mpeg2 crc64_ecma.
 * Simple: xor8 sum8 lrc8 sum16 fletcher16 fletcher8_ubx.
 *
 * The generic gmsg_crc_* functions compute bit by bit; with constant parameters the compiler folds them into the
 * loop. The presets do the same unless GMSG_CRC_TABLES is 1 (the default of the library build, see config.h):
 * then they use a 256-entry table (gmp/c/crc_tables.h, generated by runtime-c/tools/crc_tables.py). Both give the
 * same results, and the state passed between _update calls is the same in both.
 */
