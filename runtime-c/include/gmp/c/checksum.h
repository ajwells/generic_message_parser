/* Table-driven update (every preset has width >= 8): reflected shifts right, normal shifts left. */
#define GMSG_CRC_UPDATE_(name, T, width, refin, table)                                                  \
    GMSG_API T gmsg_##name##_update(T state, const uint8_t* data, size_t n) {                           \
        const T* t = gmsg_crc_table_##table##_();                                                       \
        const uint64_t mask = gmsg_crc_mask_(width);                                                    \
        uint64_t c = state;                                                                             \
        size_t i;                                                                                       \
        if (refin) {                                                                                    \
            for (i = 0; i < n; ++i) c = (c >> 8) ^ t[(c ^ data[i]) & 0xFFu];                            \
        } else {                                                                                        \
            for (i = 0; i < n; ++i) c = ((c << 8) ^ t[((c >> ((width) - 8)) ^ data[i]) & 0xFFu]) & mask; \
        }                                                                                               \
        return (T)c;                                                                                    \
    }
#else
#define GMSG_CRC_UPDATE_(name, T, width, refin, table)                                                  \
    GMSG_API T gmsg_##name##_update(T state, const uint8_t* data, size_t n) {                           \
        const gmsg_crc_params p = gmsg_##name##_params();                                               \
        return (T)gmsg_crc_update(&p, state, data, n);                                                  \
    }
#endif

#define GMSG_DEFINE_CRC_(name, T, width, poly, init, refin, refout, xorout, table)                      \
    GMSG_API gmsg_crc_params gmsg_##name##_params(void) {                                               \
        gmsg_crc_params p = {width, refin, refout, poly, init, xorout};                                 \
        return p;                                                                                       \
    }                                                                                                   \
    GMSG_API T gmsg_##name##_init(void) {                                                               \
        const gmsg_crc_params p = gmsg_##name##_params();                                               \
        return (T)gmsg_crc_init(&p);                                                                    \
    }                                                                                                   \
    GMSG_CRC_UPDATE_(name, T, width, refin, table)                                                      \
    GMSG_API T gmsg_##name##_finish(T state) {                                                          \
        const gmsg_crc_params p = gmsg_##name##_params();                                               \
        return (T)gmsg_crc_finish(&p, state);                                                           \
    }                                                                                                   \
    GMSG_API T gmsg_##name##_compute(const uint8_t* data, size_t n) {                                   \
        return gmsg_##name##_finish(gmsg_##name##_update(gmsg_##name##_init(), data, n));               \
    }

