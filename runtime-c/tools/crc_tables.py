"""Writes runtime-c/include/gmp/c/crc_tables.h: the 256-entry lookup tables of the CRC presets in checksum.h.

Run after adding or changing a preset:  py runtime-c/tools/crc_tables.py
The tables are checked against the bit-by-bit CRC by tests/runtime_c/test_c_runtime.c (every entry).
"""
import os

# (width, poly, refin): one table each; presets with the same three values share a table.
TABLES = [
    (8, 0x07, False),
    (8, 0x31, True),
    (8, 0x2F, False),
    (8, 0x31, False),
    (15, 0x4599, False),
    (16, 0x1021, False),
    (16, 0x1021, True),
    (16, 0x8005, True),
    (24, 0x864CFB, False),
    (32, 0x04C11DB7, True),
    (32, 0x1EDC6F41, True),
    (32, 0x04C11DB7, False),
    (64, 0x42F0E1EBA9EA3693, False),
]


def reflect(v, width):
    r = 0
    for _ in range(width):
        r = (r << 1) | (v & 1)
        v >>= 1
    return r


def entry(i, width, poly, refin):
    mask = (1 << width) - 1
    if refin:
        rpoly = reflect(poly, width)
        c = i
        for _ in range(8):
            c = (c >> 1) ^ rpoly if c & 1 else c >> 1
        return c
    c = i << (width - 8)
    for _ in range(8):
        c = ((c << 1) ^ poly) & mask if c >> (width - 1) & 1 else (c << 1) & mask
    return c


def ctype(width):
    return 'uint8_t' if width <= 8 else 'uint16_t' if width <= 16 else 'uint32_t' if width <= 32 else 'uint64_t'


def table_name(width, poly, refin):
    return 'w%d_%X_%s' % (width, poly, 'r' if refin else 'n')


def main():
    out = [
        '/* gmp/c/crc_tables.h - lookup tables of the CRC presets (internal; included by gmp/c/checksum.h when',
        ' * GMSG_CRC_TABLES is 1). Generated by runtime-c/tools/crc_tables.py; do not edit.',
        ' *',
        ' * gmsg_crc_table_w<width>_<poly>_<r|n>_(): r = reflected (refin), table[i] = the register after shifting i',
        ' * out (LSB first); n = normal, table[i] = the register after shifting i << (width - 8) out (MSB first).',
        ' */',
        '#ifndef GMSG_C_CRC_TABLES_H',
        '#define GMSG_C_CRC_TABLES_H',
        '',
    ]
    for width, poly, refin in TABLES:
        t = ctype(width)
        digits = (width + 3) // 4
        suffix = 'u' if width <= 32 else 'u'
        per_line = {2: 12, 4: 10, 6: 8, 8: 6, 16: 4}[max(2, ((digits + 1) // 2) * 2) if digits <= 8 else 16]
        vals = ['0x%0*X%s' % (digits, entry(i, width, poly, refin), suffix) for i in range(256)]
        out.append('GMSG_PRIV_ const %s* gmsg_crc_table_%s_(void) {' % (t, table_name(width, poly, refin)))
        out.append('    static const %s t[256] = {' % t)
        for k in range(0, 256, per_line):
            out.append('        ' + ', '.join(vals[k:k + per_line]) + ',')
        out.append('    };')
        out.append('    return t;')
        out.append('}')
        out.append('')
    out.append('#endif /* GMSG_C_CRC_TABLES_H */')
    path = os.path.join(os.path.dirname(__file__), '..', 'include', 'gmp', 'c', 'crc_tables.h')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', os.path.normpath(path))


if __name__ == '__main__':
    main()
