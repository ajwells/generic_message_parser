// C++ backend: emits a single self-contained header `<schema>.gmp.hpp` per schema.

#include "backend/cpp/cpp_backend.hpp"

#include <filesystem>
#include <set>

#include "backend/cpp/cpp_common.hpp"

namespace gmpc {

namespace {

using namespace ir;

class CppBackend final : public Backend {
public:
    [[nodiscard]] std::string_view name() const override { return "cpp"; }
    [[nodiscard]] std::string_view description() const override {
        return "C++23 header-only code using the gmp runtime (no heap, no exceptions, no RTTI)";
    }

    std::vector<OutputFile> generate(const Schema& s, const BackendOptions& /*opts*/, Diagnostics& diag) const override {
        check_lang_blocks(s, diag);
        if (diag.has_errors()) return {};

        CodeWriter w;
        cpp::Ctx c{s, diag, w};
        emit_prologue(c);
        if (!s.ns.empty()) {
            w.line("namespace " + s.ns + " {");
            w.line();
        }
        for (const auto& e : s.enums) emit_enum(c, *e);
        for (const auto& m : s.messages) {
            if (m->format == Format::Text) cpp::emit_text_message(c, *m);
            else cpp::emit_binary_message(c, *m);
        }
        for (const auto& p : s.protocols) cpp::emit_protocol(c, *p);
        if (!s.ns.empty()) w.line("} // namespace " + s.ns);
        if (diag.has_errors()) return {};
        return {OutputFile{s.stem + ".gmp.hpp", w.str()}};
    }

private:
    static void require(const LangBlocks& lang, const std::string& key, const SourceLoc& loc, const std::string& what,
                        Diagnostics& diag) {
        if (cpp::lang_value(lang, key).empty())
            diag.error(loc, what + " needs a 'cpp: { " + key + ": ... }' entry for the C++ backend");
    }

    /// Custom types / checksums / framers must define the C++ symbols they map to.
    static void check_lang_blocks(const Schema& s, Diagnostics& diag) {
        std::set<const CustomType*> used_struct;
        auto scan = [&](const Message& m) {
            for (const auto& f : m.fields) {
                const Field* x = f->kind == FieldKind::Array ? f->elem.get() : f.get();
                if (x && x->kind == FieldKind::Custom && m.want_struct) used_struct.insert(x->custom);
            }
        };
        for (const auto& m : s.messages) scan(*m);
        for (const auto& c : s.custom_types) {
            require(c->lang, "type", c->loc, "custom type '" + c->name + "'", diag);
            require(c->lang, "decode", c->loc, "custom type '" + c->name + "'", diag);
            if (used_struct.contains(c.get())) require(c->lang, "encode", c->loc, "custom type '" + c->name + "'", diag);
        }
        for (const auto& c : s.custom_checksums) require(c->lang, "function", c->loc, "custom checksum '" + c->name + "'", diag);
        for (const auto& c : s.custom_framers) require(c->lang, "type", c->loc, "custom framer '" + c->name + "'", diag);
    }

    static void emit_prologue(cpp::Ctx& c) {
        auto& w = c.w;
        w.line("// Generated by gmpc (generic message parser) from " + std::filesystem::path(c.schema.file).filename().string() + ".");
        w.line("// DO NOT EDIT - changes will be overwritten.");
        w.line("#pragma once");
        w.line();
        for (const char* h : {"<algorithm>", "<array>", "<cmath>", "<concepts>", "<cstddef>", "<cstdint>", "<limits>",
                              "<optional>", "<span>", "<string_view>", "<type_traits>", "<utility>", "<variant>"})
            w.line(std::string("#include ") + h);
        w.line();
        w.line("#include <gmp/gmp.hpp>");
        std::set<std::string> headers;
        auto add = [&](const LangBlocks& l) {
            const auto h = cpp::lang_value(l, "header");
            if (!h.empty()) headers.insert(h);
        };
        for (const auto& x : c.schema.custom_types) add(x->lang);
        for (const auto& x : c.schema.custom_checksums) add(x->lang);
        for (const auto& x : c.schema.custom_framers) add(x->lang);
        if (!headers.empty()) {
            w.line();
            w.line("// user supplied extensions");
            for (const auto& h : headers) w.line(h.front() == '<' ? "#include " + h : "#include \"" + h + "\"");
        }
        w.line();
        emit_custom_asserts(c);
    }

    /// Compile-time signature checks for user supplied codecs (clear errors instead of template noise).
    static void emit_custom_asserts(cpp::Ctx& c) {
        auto& w = c.w;
        std::set<const CustomType*> binary, text;
        for (const auto& m : c.schema.messages)
            for (const auto& f : m->fields) {
                const Field* x = f->kind == FieldKind::Array ? f->elem.get() : f.get();
                if (x && x->kind == FieldKind::Custom) (m->format == Format::Text ? text : binary).insert(x->custom);
            }
        for (const auto* ct : binary) {
            const auto t = cpp::lang_value(ct->lang, "type");
            const auto dec = cpp::lang_value(ct->lang, "decode");
            const auto enc = cpp::lang_value(ct->lang, "encode");
            w.line("static_assert(requires(gmp::ByteReader& r) { { " + dec + "(r) } -> std::same_as<gmp::Result<" + t +
                   ">>; }, \"custom type '" + ct->name + "': decode must be gmp::Result<" + t + "> (gmp::ByteReader&)\");");
            if (!enc.empty())
                w.line("static_assert(requires(gmp::ByteWriter& w, const " + t + "& v) { { " + enc +
                       "(w, v) } -> std::same_as<gmp::VoidResult>; }, \"custom type '" + ct->name +
                       "': encode must be gmp::VoidResult (gmp::ByteWriter&, const " + t + "&)\");");
        }
        for (const auto* ct : text) {
            const auto t = cpp::lang_value(ct->lang, "type");
            const auto dec = cpp::lang_value(ct->lang, "decode");
            const auto enc = cpp::lang_value(ct->lang, "encode");
            w.line("static_assert(requires(std::string_view s) { { " + dec + "(s) } -> std::same_as<gmp::Result<" + t +
                   ">>; }, \"custom text type '" + ct->name + "': decode must be gmp::Result<" + t + "> (std::string_view)\");");
            if (!enc.empty())
                w.line("static_assert(requires(gmp::text::TextWriter& w, const " + t + "& v) { { " + enc +
                       "(w, v) } -> std::same_as<gmp::VoidResult>; }, \"custom text type '" + ct->name +
                       "': encode must be gmp::VoidResult (gmp::text::TextWriter&, const " + t + "&)\");");
        }
        for (const auto& cs : c.schema.custom_checksums) {
            const auto fn = cpp::lang_value(cs->lang, "function");
            w.line("static_assert(requires(gmp::bytes_view d) { { " + fn + "(d) } -> std::unsigned_integral; }, \"custom checksum '" +
                   cs->name + "': function must be <unsigned> (gmp::bytes_view)\");");
        }
        if (!binary.empty() || !text.empty() || !c.schema.custom_checksums.empty()) w.line();
    }

    static void emit_enum(cpp::Ctx& c, const EnumDef& e) {
        auto& w = c.w;
        cpp::doc(w, e.doc);
        w.open("enum class " + e.name + " : " + cpp::prim_type(e.underlying) + " {");
        for (const auto& [n, v] : e.values) w.line(cpp::ident(n) + " = " + cpp::int_literal(v) + ",");
        w.close("};");
        w.line();
        w.open("[[nodiscard]] constexpr std::string_view to_string(" + e.name + " v) noexcept {");
        w.open("switch (v) {");
        std::set<std::int64_t> seen;
        for (const auto& [n, v] : e.values) {
            if (!seen.insert(v).second) continue;
            w.line("case " + e.name + "::" + cpp::ident(n) + ": return " + cpp::string_literal(n) + ";");
        }
        w.line("default: return {};");
        w.close();
        w.close();
        w.line();
    }
};

} // namespace

std::unique_ptr<Backend> make_cpp_backend() { return std::make_unique<CppBackend>(); }

} // namespace gmpc
