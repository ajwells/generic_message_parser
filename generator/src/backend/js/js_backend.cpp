// JavaScript backend: one module `<schema>.gmp.js` per schema, built on runtime-js/gmsg.js.
//
// The file is a UMD module: CommonJS (`require`, Node), or a classic <script> that sets a global (pages opened from
// file://, where ES modules do not load). Options:
//   --opt runtime=<module id>   how the runtime is required (default './gmsg.js'; browser: global `gmsg`)
//   --opt global=<name>         browser global for the generated module (default: namespace with '::' -> '_',
//                               else the file stem)
// Custom items bind JavaScript functions with `js: { module: '<module id>', decode: ..., encode: ..., print: ... }`
// (types), `js: { module, function }` (checksums) and `js: { module, scan }` (framers). In the browser, extension
// modules are looked up in the global object `gmsgExtensions` by module id.

#include "backend/js/js_backend.hpp"

#include <cctype>
#include <filesystem>
#include <set>

#include "backend/js/js_common.hpp"

namespace gmpc {

namespace {

using namespace ir;

class JsBackend final : public Backend {
public:
    [[nodiscard]] std::string_view name() const override { return "js"; }
    [[nodiscard]] std::string_view description() const override {
        return "JavaScript module (UMD: CommonJS or browser global) using runtime-js/gmsg.js";
    }

    std::vector<OutputFile> generate(const Schema& s, const BackendOptions& opts, Diagnostics& diag) const override {
        check_custom(s, diag);
        check_names(s, diag);
        if (diag.has_errors()) return {};

        CodeWriter body("  ");
        js::Modules modules;
        js::Consts consts;
        std::vector<std::string> exports;
        js::Ctx c{s, diag, body, modules, consts, exports};
        body.indent();
        for (const auto& e : s.enums) emit_enum(c, *e);
        for (const auto& m : s.messages) {
            if (m->format == Format::Text) js::emit_text_message(c, *m);
            else js::emit_binary_message(c, *m);
        }
        for (const auto& p : s.protocols) js::emit_protocol(c, *p);
        std::string ret = "return Object.freeze({";
        for (std::size_t i = 0; i < exports.size(); ++i) ret += (i ? ", " : " ") + exports[i];
        body.line(ret + (exports.empty() ? "});" : " });"));
        if (diag.has_errors()) return {};

        // prologue: the UMD wrapper with the runtime and the extension modules
        const auto runtime = opts.get("runtime", "./gmsg.js");
        std::string global = opts.get("global");
        if (global.empty()) {
            global = s.ns.empty() ? s.stem : s.ns;
            for (std::size_t p; (p = global.find("::")) != std::string::npos;) global.replace(p, 2, "_");
            for (auto& ch : global)
                if (!std::isalnum(static_cast<unsigned char>(ch)) && ch != '_' && ch != '$') ch = '_';
        }
        std::string cjs = "require(" + js::string_literal(runtime) + ")", browser = "root.gmsg", params = "gmsg";
        for (const auto& mod : modules.order) {
            cjs += ", require(" + js::string_literal(mod) + ")";
            browser += ", (root.gmsgExtensions || {})[" + js::string_literal(mod) + "]";
            params += ", " + modules.vars.at(mod);
        }
        CodeWriter out("  ");
        out.line("// Generated by gmpc (generic message parser) from " + std::filesystem::path(s.file).filename().string() + ".");
        out.line("// DO NOT EDIT - changes will be overwritten.");
        out.line("//");
        out.line("// CommonJS: const m = require('./" + s.stem + ".gmp.js') (the runtime is required as " + js::string_literal(runtime) + ").");
        out.line("// Browser: load gmsg.js, then this file; the module is the global `" + global + "`.");
        out.open("(function (root, factory) {");
        out.line("'use strict';");
        out.line("if (typeof module === 'object' && module.exports) module.exports = factory(" + cjs + ");");
        out.line("else root" + (global.find_first_not_of("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_$") ==
                                        std::string::npos && !std::isdigit(static_cast<unsigned char>(global[0]))
                                    ? "." + global
                                    : "[" + js::string_literal(global) + "]") +
                 " = factory(" + browser + ");");
        out.close("})(typeof globalThis !== 'undefined' ? globalThis : this, function (" + params + ") {");
        out.indent();
        out.line("'use strict';");
        out.line("const { Err } = gmsg;");
        for (const auto& [n, init] : consts.order) out.line("const " + n + " = " + init + ";");
        out.line();
        std::string text = out.str() + body.str() + "});\n";
        return {OutputFile{s.stem + ".gmp.js", text}};
    }

private:
    /// The `js:` entries of the custom items the generated code uses.
    static void check_custom(const Schema& s, Diagnostics& diag) {
        std::set<const CustomType*> types, struct_types;
        std::set<const CustomChecksum*> checksums;
        std::set<const CustomFramer*> framers;
        for (const auto& m : s.messages)
            for (const auto& f : m->fields) {
                const Field* x = f->kind == FieldKind::Array ? f->elem.get() : f.get();
                if (x && x->kind == FieldKind::Custom) {
                    types.insert(x->custom);
                    if (m->want_struct) struct_types.insert(x->custom);
                }
                if (f->crc && f->crc->custom) checksums.insert(f->crc->custom);
            }
        for (const auto& p : s.protocols) {
            if (p->checksum.present && p->checksum.custom) checksums.insert(p->checksum.custom);
            if (p->framing.type == FramingSpec::Type::Custom && p->framing.custom) framers.insert(p->framing.custom);
        }
        auto require = [&](const LangBlocks& lang, const std::string& key, const SourceLoc& loc, const std::string& what) {
            if (js::lang_value(lang, key).empty())
                diag.error(loc, what + " needs a 'js: { " + key + ": ... }' entry for the JavaScript backend");
        };
        for (const auto* t : types) {
            require(t->lang, "module", t->loc, "custom type '" + t->name + "'");
            require(t->lang, "decode", t->loc, "custom type '" + t->name + "'");
            if (struct_types.contains(t)) require(t->lang, "encode", t->loc, "custom type '" + t->name + "'");
        }
        for (const auto* c : checksums) {
            require(c->lang, "module", c->loc, "custom checksum '" + c->name + "'");
            require(c->lang, "function", c->loc, "custom checksum '" + c->name + "'");
        }
        for (const auto* f : framers) {
            require(f->lang, "module", f->loc, "custom framer '" + f->name + "'");
            require(f->lang, "scan", f->loc, "custom framer '" + f->name + "'");
        }
    }

    /// Generated classes and enums are local names of the module: they must not shadow what the code relies on.
    static void check_names(const Schema& s, Diagnostics& diag) {
        auto check = [&](const std::string& n, const SourceLoc& loc, const char* what) {
            if (js::reserved_type_name(n) || n == "Err")
                diag.error(loc, std::string(what) + " '" + n + "' clashes with a JavaScript name used by the generated module; rename it");
        };
        for (const auto& e : s.enums) check(e->name, e->loc, "enum");
        for (const auto& m : s.messages) check(m->name, m->loc, "message");
        for (const auto& p : s.protocols) check(p->name, p->loc, "protocol");
    }

    static void emit_enum(js::Ctx& c, const EnumDef& e) {
        auto& w = c.w;
        js::doc(w, e.doc);
        std::string entries;
        for (const auto& [n, v] : e.values)
            entries += (entries.empty() ? "" : ", ") + std::string("[") + js::string_literal(n) + ", " + js::int_literal(v, e.underlying) + "]";
        w.line("const " + e.name + " = gmsg.enumType(" + js::string_literal(e.name) + ", '" + js::prim_id(e.underlying) + "', [" +
               entries + "], " + (e.strict ? "true" : "false") + ");");
        w.line();
        c.exports.push_back(e.name);
    }
};

} // namespace

std::unique_ptr<Backend> make_js_backend() { return std::make_unique<JsBackend>(); }

} // namespace gmpc
