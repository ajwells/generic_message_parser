// Python backend: one module `<schema>_gmp.py` per schema, built on the runtime package `gmsg` (runtime-py).
//
// Options:
//   --opt runtime=<module>   the runtime package to import (default gmsg; e.g. mypkg.gmsg for a vendored copy)
// Custom items bind Python functions with `python: { module: <module>, decode: ..., encode: ..., print: ... }` (types),
// `python: { module, function }` (checksums) and `python: { module, scan }` (framers). A module starting with '.' is
// imported relative to the generated module's package (`.codecs` -> `from . import codecs`).

#include "backend/py/py_backend.hpp"

#include <cctype>
#include <filesystem>
#include <set>

#include "backend/py/py_common.hpp"

namespace gmpc {

namespace {

using namespace ir;

/// The import statement binding `module` to `var`.
std::string import_line(const std::string& module, const std::string& var) {
    if (module.empty() || module[0] != '.') return "import " + module + " as " + var;
    const auto dot = module.find_last_of('.');
    const auto pkg = module.substr(0, dot), name = module.substr(dot + 1);
    return "from " + (pkg.empty() ? std::string(".") : pkg) + " import " + name + " as " + var;
}

class PyBackend final : public Backend {
public:
    [[nodiscard]] std::string_view name() const override { return "python"; }
    [[nodiscard]] std::string_view description() const override {
        return "Python 3.12+ module (dataclasses) using the runtime package gmsg (runtime-py)";
    }

    std::vector<OutputFile> generate(const Schema& s, const BackendOptions& opts, Diagnostics& diag) const override {
        check_custom(s, diag);
        check_names(s, diag);
        if (diag.has_errors()) return {};

        CodeWriter body("    ");
        py::Modules modules;
        py::Consts consts;
        std::vector<std::string> exports;
        py::Ctx c{s, diag, body, modules, consts, exports};
        for (const auto& e : s.enums) emit_enum(c, *e);
        for (const auto& m : s.messages) {
            if (m->format == Format::Text) py::emit_text_message(c, *m);
            else py::emit_binary_message(c, *m);
        }
        for (const auto& p : s.protocols) py::emit_protocol(c, *p);
        if (diag.has_errors()) return {};

        const auto runtime = opts.get("runtime", "gmsg");
        const auto file = std::filesystem::path(s.file).filename().string();
        CodeWriter out("    ");
        out.line("# Generated by gmpc (generic message parser) from " + file + ".");
        out.line("# DO NOT EDIT - changes will be overwritten.");
        out.line("#");
        out.line("# Needs Python 3.12+ and the runtime package `" + runtime + "` (runtime-py; its optional accelerator gmsg._native");
        out.line("# is used when installed).");
        out.line("\"\"\"Messages" + (s.ns.empty() ? std::string() : " of " + s.ns) + " (" + file + ").\"\"\"");
        out.line();
        out.line("from __future__ import annotations");
        out.line();
        bool structs = false;
        for (const auto& kv : consts.order) structs = structs || kv.first.starts_with("_st");
        if (structs) out.line("import struct as _struct");
        out.line("from dataclasses import dataclass as _dataclass");
        out.line("from dataclasses import field as _field");
        out.line("from typing import ClassVar as _ClassVar");
        out.line();
        if (runtime == "gmsg") out.line("import gmsg");
        else out.line("import " + runtime + " as gmsg");
        out.line("from gmsg import Err");
        if (runtime != "gmsg") out.line("Err = gmsg.Err");
        for (const auto& mod : modules.order) out.line(import_line(mod, modules.vars.at(mod)));
        out.line();
        for (const auto& [n, init] : consts.order) out.line(n + " = " + init);
        std::string all;
        for (const auto& e : exports) all += (all.empty() ? "" : ", ") + py::string_literal(e);
        out.line("__all__ = [" + all + "]");
        out.line();
        out.line();
        std::string text = out.str() + body.str();
        while (text.size() > 1 && text[text.size() - 1] == '\n' && text[text.size() - 2] == '\n') text.pop_back();
        return {OutputFile{module_name(s.stem) + ".py", text}};
    }

    /// `<stem>_gmp`, with characters that cannot appear in a Python module name replaced by '_'.
    static std::string module_name(const std::string& stem) {
        std::string n = stem + "_gmp";
        for (auto& ch : n)
            if (!std::isalnum(static_cast<unsigned char>(ch)) && ch != '_') ch = '_';
        if (std::isdigit(static_cast<unsigned char>(n[0]))) n = "_" + n;
        return n;
    }

private:
    /// The `python:` entries of the custom items the generated code uses.
    static void check_custom(const Schema& s, Diagnostics& diag) {
        std::set<const CustomType*> types, struct_types;
        std::set<const CustomChecksum*> checksums;
        std::set<const CustomFramer*> framers;
        for (const auto& m : s.messages)
            for (const auto& f : m->fields) {
                const Field* x = f->kind == FieldKind::Array ? f->elem.get() : f.get();
                if (x && x->kind == FieldKind::Custom) {
                    types.insert(x->custom);
                    if (m->want_struct) struct_types.insert(x->custom);
                }
                if (f->crc && f->crc->custom) checksums.insert(f->crc->custom);
            }
        for (const auto& p : s.protocols) {
            if (p->checksum.present && p->checksum.custom) checksums.insert(p->checksum.custom);
            if (p->framing.type == FramingSpec::Type::Custom && p->framing.custom) framers.insert(p->framing.custom);
        }
        auto require = [&](const LangBlocks& lang, const std::string& key, const SourceLoc& loc, const std::string& what) {
            if (py::lang_value(lang, key).empty())
                diag.error(loc, what + " needs a 'python: { " + key + ": ... }' entry for the Python backend");
        };
        for (const auto* t : types) {
            require(t->lang, "module", t->loc, "custom type '" + t->name + "'");
            require(t->lang, "decode", t->loc, "custom type '" + t->name + "'");
            if (struct_types.contains(t)) require(t->lang, "encode", t->loc, "custom type '" + t->name + "'");
        }
        for (const auto* c : checksums) {
            require(c->lang, "module", c->loc, "custom checksum '" + c->name + "'");
            require(c->lang, "function", c->loc, "custom checksum '" + c->name + "'");
        }
        for (const auto* f : framers) {
            require(f->lang, "module", f->loc, "custom framer '" + f->name + "'");
            require(f->lang, "scan", f->loc, "custom framer '" + f->name + "'");
        }
    }

    /// Generated classes and enums are module-level names: they must not shadow what the code relies on.
    static void check_names(const Schema& s, Diagnostics& diag) {
        auto check = [&](const std::string& n, const SourceLoc& loc, const char* what) {
            if (py::reserved_type_name(n))
                diag.error(loc, std::string(what) + " '" + n + "' clashes with a Python name used by the generated module; rename it");
        };
        for (const auto& e : s.enums) check(e->name, e->loc, "enum");
        for (const auto& m : s.messages) check(m->name, m->loc, "message");
        for (const auto& p : s.protocols) check(p->name, p->loc, "protocol");
    }

    static void emit_enum(py::Ctx& c, const EnumDef& e) {
        auto& w = c.w;
        w.open("class " + e.name + "(gmsg.GmpEnum):");
        py::doc(w, e.doc);
        std::string renamed;
        for (const auto& [n, v] : e.values) {
            const auto id = py::enum_ident(n);
            w.line(id + " = " + py::int_literal(v, e.underlying));
            if (id != n) renamed += (renamed.empty() ? "" : ", ") + py::string_literal(id) + ": " + py::string_literal(n);
        }
        if (!renamed.empty()) w.line("__gmp_names__ = {" + renamed + "}");
        if (e.values.empty()) w.line("pass");
        w.dedent();
        w.line();
        w.line();
        c.exports.push_back(e.name);
    }
};

} // namespace

std::unique_ptr<Backend> make_py_backend() { return std::make_unique<PyBackend>(); }

} // namespace gmpc
